using System;
using System.Collections.Generic;
using System.Linq;
using Internal.EditorTests.Menu;
using NUnit.Framework;
using UnityEngine;
using Object = UnityEngine.Object;

namespace Internal.EditorTests
{
    // What the scanner mirrors and how the code generator writes it, on objects in memory.
    public class HierarchyBindingsScannerTests
    {
        private const string Namespace = "Generated.Tests";

        private readonly List<GameObject> _created = new();

        [TearDown]
        public void TearDown()
        {
            foreach (var target in _created)
                Object.DestroyImmediate(target);

            _created.Clear();
        }

        [Test]
        public void PlainHierarchy_WholeText()
        {
            var root = Root("Card");
            Child(root, "Title");

            var node = Scan(root, "CardBindings");
            var hash = HierarchyBindingsStructure.ComputeHash(node);

            var expected = string.Join(Environment.NewLine,
                "// <auto-generated/>",
                "// Auto-generated by HierarchyBindingsGenerator. Do not edit manually.",
                "using System;",
                "using UnityEngine;",
                "",
                "namespace Generated.Tests {",
                $"    // Structure: {hash}",
                "    // Card",
                "    //   - Title",
                "    [DisallowMultipleComponent]",
                "    public class CardBindings : global::Internal.ObjectBindings {",
                "        [SerializeField, HideInInspector] private global::UnityEngine.GameObject _gameObject;",
                "        [SerializeField, HideInInspector] private global::UnityEngine.Transform _transform;",
                "",
                "        // Child objects",
                "        [SerializeField, HideInInspector] private TitleBindings _title;",
                "",
                "        public global::UnityEngine.GameObject GameObject => _gameObject;",
                "        public global::UnityEngine.Transform Transform => _transform;",
                "        public TitleBindings Title => _title;",
                "",
                "        // Card/Title",
                "        [Serializable]",
                "        public sealed class TitleBindings {",
                "            [SerializeField, HideInInspector] private global::UnityEngine.GameObject _gameObject;",
                "            [SerializeField, HideInInspector] private global::UnityEngine.Transform _transform;",
                "",
                "            public global::UnityEngine.GameObject GameObject => _gameObject;",
                "            public global::UnityEngine.Transform Transform => _transform;",
                "        }",
                "    }",
                "}",
                "");

            Assert.That(Build(node), Is.EqualTo(expected));
        }

        [Test]
        public void WithoutNamespace_NoNamespaceLine()
        {
            var code = HierarchyBindingsCodeGenerator.Build(Scan(Root("Card"), "CardBindings"), string.Empty, "hash",
                false, false);

            Assert.That(code, Does.Not.Contain("namespace"));
            Assert.That(code, Does.Contain($"{Environment.NewLine}// Structure: hash{Environment.NewLine}"));
        }

        [Test]
        public void SceneService_GetsCreate()
        {
            var code = Build(Scan(Root("Hud"), "HudBindings", true), true);

            Assert.That(code, Does.Contain("HudBindings : global::Internal.ObjectBindings, global::Internal.ISceneService {"));
            Assert.That(code, Does.Contain("public virtual void Create(global::Internal.IScopeBuilder builder) {"));
            Assert.That(code, Does.Not.Contain("Register("));
        }

        [Test]
        public void EntityComponent_GetsRegister()
        {
            var code = Build(Scan(Root("Hero"), "HeroBindings", false, true), false, true);

            Assert.That(code, Does.Contain("HeroBindings : global::Internal.ObjectBindings, global::Internal.IEntityComponent {"));
            Assert.That(code, Does.Contain("public virtual void Register(global::Internal.IEntityBuilder builder) {"));
            Assert.That(code, Does.Not.Contain("Create("));
        }

        [Test]
        public void ThreeSiblings_CollapseIntoArray()
        {
            var root = Root("List");
            Child(root, "Entry");
            Child(root, "Entry (1)");
            Child(root, "Entry_2");

            var node = Scan(root, "ListBindings");
            var code = Build(node);

            Assert.That(node.Children, Has.Count.EqualTo(1));
            Assert.That(node.Children[0].Elements, Has.Count.EqualTo(3));
            Assert.That(code, Does.Contain("public EntryBindings[] Entries => _entries;"));
            Assert.That(code, Does.Contain("//   - Entry .. Entry_2 (3 items)"));
            Assert.That(code, Does.Contain("// List/Entry .. Entry_2 (3 items)"));
        }

        // A pair is usually named on purpose (Left / Right).
        [Test]
        public void TwoSiblings_StaySeparate()
        {
            var root = Root("List");
            Child(root, "Entry");
            Child(root, "Entry (1)");

            var node = Scan(root, "ListBindings");

            Assert.That(node.Children.Select(child => child.PropertyName), Is.EqualTo(new[] { "Entry", "Entry1" }));
            Assert.That(node.Children.Any(child => child.IsArray), Is.False);
        }

        [Test]
        public void SiblingWithOtherContents_BreaksTheRow()
        {
            var root = Root("List");
            Child(root, "Entry");
            Child(root, "Entry (1)");
            Child(Child(root, "Entry (2)"), "Icon");
            Child(root, "Entry (3)");

            var node = Scan(root, "ListBindings");

            Assert.That(node.Children, Has.Count.EqualTo(4));
            Assert.That(node.Children.Any(child => child.IsArray), Is.False);
        }

        [TestCase("City", "Cities")]
        [TestCase("Box", "Boxes")]
        [TestCase("Key", "Keys")]
        public void Row_GetsPluralName(string name, string plural)
        {
            var root = Root("List");

            for (var index = 0; index < 3; index++)
                Child(root, $"{name} ({index})");

            Assert.That(Scan(root, "ListBindings").Children[0].PropertyName, Is.EqualTo(plural));
        }

        [Test]
        public void IgnoreChildren_KeepsTheObjectCutsTheBranch()
        {
            var root = Root("Window");
            var panel = Child(root, "Panel");
            panel.AddComponent<HierarchyBindingsIgnoreChildren>();
            Child(panel, "Inner");

            var node = Scan(root, "WindowBindings");
            var code = Build(node);

            Assert.That(node.Children.Single().IgnoreChildren, Is.True);
            Assert.That(node.Children.Single().Children, Is.Empty);
            Assert.That(code, Does.Contain("//   - Panel (children ignored)"));
            Assert.That(code, Does.Not.Contain("InnerBindings"));
        }

        [Test]
        public void SevenLevels_AreMirrored_DeeperIsAnError()
        {
            var fits = Root("Fits");
            Chain(fits, HierarchyBindingsScanner.MaxNestingDepth);
            Assert.That(Scan(fits, "FitsBindings"), Is.Not.Null);

            var tooDeep = Root("TooDeep");
            Chain(tooDeep, HierarchyBindingsScanner.MaxNestingDepth + 1);

            Assert.That(ScanErrors(tooDeep, "TooDeepBindings").Single(), Does.Contain("deeper than 7 levels"));
        }

        [Test]
        public void NameWithoutIdentifier_IsAnError()
        {
            var root = Root("Window");
            Child(root, "!!!");

            Assert.That(ScanErrors(root, "WindowBindings").Single(), Does.Contain("'!!!' is not a C# identifier"));
        }

        [Test]
        public void NameOfOwnRegistrationMethod_IsAnError()
        {
            var root = Root("Hero");
            Child(root, "Register");

            Assert.That(ScanErrors(root, "HeroBindings", false, true).Single(), Does.Contain("collides with a member"));
        }

        [Test]
        public void NullRoot_IsAnError()
        {
            Assert.That(ScanErrors(null, "NoBindings").Single(), Is.EqualTo("Object is null."));
        }

        // HPBar and HpBar both give _hpBar: the second one takes a number.
        [Test]
        public void SameFieldName_TakesASuffix()
        {
            var root = Root("Status");
            Child(root, "HPBar");
            Child(root, "HpBar");

            Assert.That(Scan(root, "StatusBindings").Children.Select(child => child.PropertyName),
                Is.EqualTo(new[] { "HPBar", "HpBar2" }));
        }

        [Test]
        public void Components_MirroredExceptTheSkippedOnes()
        {
            var root = Root("Window");
            root.AddComponent<Camera>();
            root.AddComponent<CanvasRenderer>();
            root.AddComponent<AudioSource>().hideFlags = HideFlags.DontSaveInEditor;

            var fields = Scan(root, "WindowBindings").Fields.Select(field => field.PropertyName);

            Assert.That(fields, Is.EqualTo(new[] { "GameObject", "Transform", "Camera" }));
        }

        [Test]
        public void ChildWithOwnBindings_IsAReference()
        {
            var root = Root("Window");
            var shop = Child(root, "Shop");
            shop.AddComponent<ShopBindings>();
            Child(shop, "Inner");

            var node = Scan(root, "WindowBindings");
            var code = Build(node);

            Assert.That(node.Children, Is.Empty);
            Assert.That(code, Does.Contain("// Window/Shop (own bindings)"));
            Assert.That(code, Does.Contain($"private {ShopType} _shop;"));
            Assert.That(code, Does.Contain("//   - Shop (own bindings)"));
            Assert.That(code, Does.Not.Contain("Inner"));
        }

        [Test]
        public void RowWithOwnBindings_IsAnArrayOfReferences()
        {
            var root = Root("Window");

            for (var index = 0; index < 3; index++)
                Child(root, $"Slot ({index})").AddComponent<ShopBindings>();

            var node = Scan(root, "WindowBindings");
            var code = Build(node);

            Assert.That(node.Fields.Single(field => field.PropertyName == "Slots").Targets, Has.Count.EqualTo(3));
            Assert.That(code, Does.Contain($"private {ShopType}[] _slots;"));
            Assert.That(code, Does.Contain("//   - Slot (0) .. Slot (2) (3 items, own bindings)"));
        }

        [Test]
        public void ChildWithSeveralBindings_GetsAFieldPerClass()
        {
            var root = Root("Window");
            var pair = Child(root, "Pair");
            pair.AddComponent<ShopBindings>();
            pair.AddComponent<ExtraBindings>();

            var names = Scan(root, "WindowBindings").Fields.Select(field => field.PropertyName);

            Assert.That(names, Is.EqualTo(new[] { "GameObject", "Transform", "PairShop", "PairExtra" }));
        }

        // The order of the components is not part of the signature: an element is found by type.
        [Test]
        public void RowWithSeveralBindings_FindsElementsByType()
        {
            var root = Root("Window");
            var first = Child(root, "Slot (0)");
            first.AddComponent<ShopBindings>();
            first.AddComponent<ExtraBindings>();
            var second = Child(root, "Slot (1)");
            second.AddComponent<ExtraBindings>();
            second.AddComponent<ShopBindings>();
            var third = Child(root, "Slot (2)");
            third.AddComponent<ShopBindings>();
            third.AddComponent<ExtraBindings>();

            var field = Scan(root, "WindowBindings").Fields.Single(candidate => candidate.PropertyName == "SlotsExtra");

            Assert.That(field.Targets, Is.EqualTo(new Object[]
            {
                first.GetComponent<ExtraBindings>(),
                second.GetComponent<ExtraBindings>(),
                third.GetComponent<ExtraBindings>()
            }));
        }

        [Test]
        public void FieldOfSeveralBindings_TakenBySibling_IsAnError()
        {
            var root = Root("Window");
            var pair = Child(root, "Pair");
            pair.AddComponent<ShopBindings>();
            pair.AddComponent<ExtraBindings>();
            Child(root, "PairShop");

            Assert.That(ScanErrors(root, "WindowBindings").Single(), Does.Contain("'PairShop' for one of its bindings"));
        }

        [Test]
        public void SameBindingsTwiceOnChild_IsAnError()
        {
            var root = Root("Window");
            var pair = Child(root, "Pair");
            pair.AddComponent<ExtraBindings>();
            pair.AddComponent<ExtraBindings>();

            Assert.That(ScanErrors(root, "WindowBindings").Single(), Does.Contain("carries ExtraBindings twice"));
        }

        private const string ShopType = "global::Internal.EditorTests.Menu.ShopBindings";

        private GameObject Root(string name)
        {
            var root = new GameObject(name);
            _created.Add(root);
            return root;
        }

        private static GameObject Child(GameObject parent, string name)
        {
            var child = new GameObject(name);
            child.transform.SetParent(parent.transform, false);
            return child;
        }

        private static void Chain(GameObject root, int length)
        {
            var current = root;

            for (var index = 0; index < length; index++)
                current = Child(current, "Level" + index);
        }

        private static HierarchyBindingsNode Scan(
            GameObject root,
            string typeName,
            bool isSceneService = false,
            bool isEntityComponent = false)
        {
            var errors = new List<string>();
            var layer = HierarchyBindingsLayer.Resolve(string.Empty, false);
            var node = HierarchyBindingsScanner.Scan(root, typeName, layer, errors, isSceneService, isEntityComponent);

            Assert.That(errors, Is.Empty);
            return node;
        }

        private static List<string> ScanErrors(
            GameObject root,
            string typeName,
            bool isSceneService = false,
            bool isEntityComponent = false)
        {
            var errors = new List<string>();
            var layer = HierarchyBindingsLayer.Resolve(string.Empty, false);
            var node = HierarchyBindingsScanner.Scan(root, typeName, layer, errors, isSceneService, isEntityComponent);

            Assert.That(node, Is.Null);
            return errors;
        }

        private static string Build(
            HierarchyBindingsNode node,
            bool isSceneService = false,
            bool isEntityComponent = false)
        {
            return HierarchyBindingsCodeGenerator.Build(node, Namespace, HierarchyBindingsStructure.ComputeHash(node),
                isSceneService, isEntityComponent);
        }
    }
}
