using System;
using System.Collections.Generic;
using System.Text;
using UnityEngine;

namespace Internal
{
    public static class SpritesClassGenerator
    {
        public static string GeneratedFolder => FrameworkSettings.Content("Runtime/Catalogues/Sprites");

        private const string LogTag = "SpritesClassGenerator";

        internal static void Generate(IReadOnlyList<SpriteGroupDefinition> groups)
        {
            CatalogPaths.EnsureFolder(GeneratedFolder);

            var sources = BuildSources(groups);
            var written = new HashSet<string>(StringComparer.Ordinal);

            foreach (var pair in sources)
            {
                written.Add(pair.Key);
                GeneratedFile.WriteIfChanged(LogTag, $"{GeneratedFolder}/{pair.Key}", pair.Value);
            }

            GeneratedFile.DeleteStale(LogTag, GeneratedFolder, written, ".cs");
        }

        // File name -> source of every class of the catalogue.
        internal static Dictionary<string, string> BuildSources(IReadOnlyList<SpriteGroupDefinition> groups)
        {
            var root = BuildTree(groups);
            var sources = new Dictionary<string, string>(StringComparer.Ordinal)
            {
                { "Sprites.cs", BuildSpritesClass(root) }
            };

            foreach (var node in EnumerateNodes(root))
                sources.Add(node.ClassName + ".cs", node.Group != null ? BuildGroupClass(node) : BuildNodeClass(node));

            return sources;
        }

        // Group path "Game.Players" is laid out as a tree: Sprites.Game.Players.
        // An intermediate node without its own group is just a container for nested ones.
        private static Node BuildTree(IReadOnlyList<SpriteGroupDefinition> groups)
        {
            var root = new Node(string.Empty, string.Empty);

            foreach (var group in groups)
            {
                var node = root;

                foreach (var segment in group.Path.Split('.'))
                {
                    if (node.Children.TryGetValue(segment, out var child) == false)
                    {
                        var path = node.Path.Length == 0 ? segment : node.Path + "." + segment;
                        child = new Node(segment, path);
                        node.Children.Add(segment, child);
                    }

                    node = child;
                }

                node.Group = group;
            }

            foreach (var node in EnumerateNodes(root))
                RemoveConflictingChildren(node);

            return root;
        }

        private static void RemoveConflictingChildren(Node node)
        {
            if (node.Group == null)
                return;

            var members = new HashSet<string>(StringComparer.Ordinal);

            foreach (var property in node.Group.Properties)
                members.Add(property.Owner ?? property.PropertyName);

            var conflicts = new List<string>();

            foreach (var name in node.Children.Keys)
            {
                if (members.Contains(name))
                    conflicts.Add(name);
            }

            foreach (var name in conflicts)
            {
                Debug.LogError(
                        $"[{LogTag}] Group '{node.Path}.{name}' conflicts with a sprite of group '{node.Path}'. Skipping the nested group."
                    );
                node.Children.Remove(name);
            }
        }

        private static IEnumerable<Node> EnumerateNodes(Node root)
        {
            foreach (var child in root.Children.Values)
            {
                yield return child;

                foreach (var nested in EnumerateNodes(child))
                    yield return nested;
            }
        }

        private static string BuildSpritesClass(Node root)
        {
            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by SpriteGenerator. Do not edit manually.");
            builder.AppendLine("using Unity.Scripting.LifecycleManagement;");
            builder.AppendLine();
            builder.AppendLine("namespace Internal {");
            builder.AppendLine("    [NoAutoStaticsCleanup]");
            builder.AppendLine("    public static class Sprites {");

            var members = new IdentifierScope("Sprites", Array.Empty<string>());

            foreach (var child in root.Children.Values)
            {
                members.Declare(child.Name, $"Sprite group '{child.Path}'");
                builder.AppendLine($"        public static readonly {child.ClassName} {child.Name} = new();");
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        private static string BuildNodeClass(Node node)
        {
            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by SpriteGenerator. Do not edit manually.");
            builder.AppendLine();
            builder.AppendLine("namespace Internal {");
            builder.AppendLine($"    public sealed class {node.ClassName} {{");

            var members = new IdentifierScope(node.ClassName, CodeIdentifiers.InheritedMembers(typeof(object)));

            foreach (var child in node.Children.Values)
            {
                members.Declare(child.Name, $"Sprite group '{child.Path}'");
                builder.AppendLine($"        public readonly {child.ClassName} {child.Name} = new();");
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        private static string BuildGroupClass(Node node)
        {
            var group = node.Group;
            var flat = new List<SpritePropertyDefinition>();
            var owners = new SortedDictionary<string, List<SpritePropertyDefinition>>(StringComparer.Ordinal);
            var hasSheet = false;

            foreach (var property in group.Properties)
            {
                if (property.Kind != SpriteKind.Animation)
                    hasSheet = true;

                if (property.Owner == null)
                {
                    flat.Add(property);
                    continue;
                }

                if (owners.TryGetValue(property.Owner, out var members) == false)
                {
                    members = new List<SpritePropertyDefinition>();
                    owners.Add(property.Owner, members);
                }

                members.Add(property);
            }

            DeclareMembers(node, flat, owners);

            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by SpriteGenerator. Do not edit manually.");
            builder.AppendLine("using Cysharp.Threading.Tasks;");

            if (hasSheet)
                builder.AppendLine("using UnityEngine;");
            builder.AppendLine();
            builder.AppendLine("namespace Internal {");
            builder.AppendLine($"    public sealed class {group.ClassName} : SpriteGroup {{");
            builder.AppendLine($"        private const string Address = \"{group.Address}\";");
            builder.AppendLine();

            foreach (var child in node.Children.Values)
                builder.AppendLine($"        public readonly {child.ClassName} {child.Name} = new();");

            if (node.Children.Count > 0)
                builder.AppendLine();

            foreach (var property in flat)
                builder.AppendLine($"        private {PropertyType(property.Kind)} {property.FieldName};");

            if (flat.Count > 0)
                builder.AppendLine();

            if (owners.Count > 0)
            {
                builder.AppendLine($"        public {group.ClassName}() {{");

                foreach (var owner in owners.Keys)
                    builder.AppendLine($"            {owner} = new {owner}Sprites(this);");

                builder.AppendLine("        }");
                builder.AppendLine();

                foreach (var owner in owners.Keys)
                    builder.AppendLine($"        public {owner}Sprites {owner} {{ get; }}");

                builder.AppendLine();
            }

            foreach (var property in flat)
            {
                builder.AppendLine($"        public {PropertyType(property.Kind)} {property.PropertyName} {{");
                builder.AppendLine($"            get {{ EnsureLoaded(); return {property.FieldName}; }}");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            builder.AppendLine("        protected override async UniTask LoadGroup() {");
            builder.AppendLine("            await LoadAsset(Address);");

            foreach (var property in flat)
                builder.AppendLine($"            {property.FieldName} = Asset.{Getter(property.Kind)}(\"{property.PropertyName}\");");

            foreach (var pair in owners)
            {
                foreach (var property in pair.Value)
                    builder.AppendLine(
                            $"            {pair.Key}.{property.FieldName} = Asset.{Getter(property.Kind)}(\"{property.PropertyName}\");"
                        );
            }

            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        protected override void UnloadGroup() {");

            foreach (var property in flat)
                builder.AppendLine($"            {property.FieldName} = null;");

            foreach (var pair in owners)
            {
                foreach (var property in pair.Value)
                    builder.AppendLine($"            {pair.Key}.{property.FieldName} = null;");
            }

            builder.AppendLine("            UnloadAsset();");
            builder.AppendLine("        }");

            foreach (var pair in owners)
            {
                builder.AppendLine();
                BuildOwnerClass(builder, pair.Key, pair.Value);
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        // The members of the group class: the nested groups, the sprites, the objects of the Multiple Animations
        // files with their classes, and inside each such class its animations.
        private static void DeclareMembers(
            Node node,
            List<SpritePropertyDefinition> flat,
            SortedDictionary<string, List<SpritePropertyDefinition>> owners)
        {
            var group = node.Group;
            var source = $"Sprite group '{group.Path}'";
            var reserved = new List<string>(CodeIdentifiers.InheritedMembers(typeof(SpriteGroup))) { "Address" };
            var members = new IdentifierScope(group.ClassName, reserved);

            foreach (var child in node.Children.Values)
                members.Declare(child.Name, source);

            foreach (var property in flat)
            {
                members.Declare(property.PropertyName, source);
                members.Declare(property.FieldName, source);
            }

            foreach (var pair in owners)
            {
                var ownerClass = pair.Key + "Sprites";
                members.Declare(pair.Key, source);
                members.Declare(ownerClass, source);

                var ownerMembers = new IdentifierScope(ownerClass,
                    new List<string>(CodeIdentifiers.InheritedMembers(typeof(object))) { "_group" });

                foreach (var property in pair.Value)
                {
                    ownerMembers.Declare(property.MemberName, $"{source}, animations of '{pair.Key}'");
                    ownerMembers.Declare(property.FieldName, $"{source}, animations of '{pair.Key}'");
                }
            }
        }

        // Animations of one Multiple Animations file. They are loaded together with the group,
        // so access to them checks that the group is loaded.
        private static void BuildOwnerClass(
            StringBuilder builder,
            string owner,
            IReadOnlyList<SpritePropertyDefinition> members)
        {
            builder.AppendLine($"        public sealed class {owner}Sprites {{");
            builder.AppendLine("            private readonly SpriteGroup _group;");
            builder.AppendLine();

            foreach (var property in members)
                builder.AppendLine($"            internal {PropertyType(property.Kind)} {property.FieldName};");

            builder.AppendLine();
            builder.AppendLine($"            internal {owner}Sprites(SpriteGroup group) {{");
            builder.AppendLine("                _group = group;");
            builder.AppendLine("            }");

            foreach (var property in members)
            {
                builder.AppendLine();
                builder.AppendLine($"            public {PropertyType(property.Kind)} {property.MemberName} {{");
                builder.AppendLine($"                get {{ _group.EnsureLoaded(); return {property.FieldName}; }}");
                builder.AppendLine("            }");
            }

            builder.AppendLine("        }");
        }

        private static string Getter(SpriteKind kind)
        {
            return kind == SpriteKind.Animation ? "GetAnimation" : "GetSheet";
        }

        private static string PropertyType(SpriteKind kind)
        {
            return kind == SpriteKind.Animation ? "ISpriteAnimationData" : "Sprite";
        }

        private sealed class Node
        {
            public Node(string name, string path)
            {
                Name = name;
                Path = path;
            }

            public string Name { get; }
            public string Path { get; }
            public SpriteGroupDefinition Group { get; set; }
            public SortedDictionary<string, Node> Children { get; } = new(StringComparer.Ordinal);

            public string ClassName => Group != null ? Group.ClassName : SpriteGenerator.ToGroupKey(Path) + "Sprites";
        }
    }
}
