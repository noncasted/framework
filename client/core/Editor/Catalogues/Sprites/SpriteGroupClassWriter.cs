using System;
using System.Collections.Generic;
using System.Text;

namespace Internal
{
    // The class of one group with its own sprites, nested groups and Multiple Animations objects.
    internal static class SpriteGroupClassWriter
    {
        internal static string BuildGroupClass(SpriteGroupNode node)
        {
            var group = node.Group;
            var flat = new List<SpritePropertyDefinition>();
            var owners = new SortedDictionary<string, List<SpritePropertyDefinition>>(StringComparer.Ordinal);
            var hasSheet = false;

            foreach (var property in group.Properties)
            {
                if (property.Kind != SpriteKind.Animation)
                    hasSheet = true;

                if (property.Owner == null)
                {
                    flat.Add(property);
                    continue;
                }

                if (owners.TryGetValue(property.Owner, out var members) == false)
                {
                    members = new List<SpritePropertyDefinition>();
                    owners.Add(property.Owner, members);
                }

                members.Add(property);
            }

            DeclareMembers(node, flat, owners);

            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by SpriteGenerator. Do not edit manually.");
            builder.AppendLine("using Cysharp.Threading.Tasks;");

            if (hasSheet)
                builder.AppendLine("using UnityEngine;");
            builder.AppendLine();
            builder.AppendLine("namespace Internal {");
            builder.AppendLine($"    public sealed class {group.ClassName} : SpriteGroup {{");
            builder.AppendLine($"        private const string Address = \"{group.Address}\";");
            builder.AppendLine();

            foreach (var child in node.Children.Values)
                builder.AppendLine($"        public readonly {child.ClassName} {child.Name} = new();");

            if (node.Children.Count > 0)
                builder.AppendLine();

            foreach (var property in flat)
                builder.AppendLine($"        private {PropertyType(property.Kind)} {property.FieldName};");

            if (flat.Count > 0)
                builder.AppendLine();

            if (owners.Count > 0)
            {
                builder.AppendLine($"        public {group.ClassName}() {{");

                foreach (var owner in owners.Keys)
                    builder.AppendLine($"            {owner} = new {owner}Sprites(this);");

                builder.AppendLine("        }");
                builder.AppendLine();

                foreach (var owner in owners.Keys)
                    builder.AppendLine($"        public {owner}Sprites {owner} {{ get; }}");

                builder.AppendLine();
            }

            foreach (var property in flat)
            {
                builder.AppendLine($"        public {PropertyType(property.Kind)} {property.PropertyName} {{");
                builder.AppendLine($"            get {{ EnsureLoaded(); return {property.FieldName}; }}");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            builder.AppendLine("        protected override async UniTask LoadGroup() {");
            builder.AppendLine("            await LoadAsset(Address);");

            foreach (var property in flat)
                builder.AppendLine($"            {property.FieldName} = Asset.{Getter(property.Kind)}(\"{property.PropertyName}\");");

            foreach (var pair in owners)
            {
                foreach (var property in pair.Value)
                    builder.AppendLine(
                            $"            {pair.Key}.{property.FieldName} = Asset.{Getter(property.Kind)}(\"{property.PropertyName}\");"
                        );
            }

            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        protected override void UnloadGroup() {");

            foreach (var property in flat)
                builder.AppendLine($"            {property.FieldName} = null;");

            foreach (var pair in owners)
            {
                foreach (var property in pair.Value)
                    builder.AppendLine($"            {pair.Key}.{property.FieldName} = null;");
            }

            builder.AppendLine("            UnloadAsset();");
            builder.AppendLine("        }");

            foreach (var pair in owners)
            {
                builder.AppendLine();
                BuildOwnerClass(builder, pair.Key, pair.Value);
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        // The members of the group class: the nested groups, the sprites, the objects of the Multiple Animations
        // files with their classes, and inside each such class its animations.
        private static void DeclareMembers(
            SpriteGroupNode node,
            List<SpritePropertyDefinition> flat,
            SortedDictionary<string, List<SpritePropertyDefinition>> owners)
        {
            var group = node.Group;
            var source = $"Sprite group '{group.Path}'";
            var reserved = new List<string>(CodeIdentifiers.InheritedMembers(typeof(SpriteGroup))) { "Address" };
            var members = new IdentifierScope(group.ClassName, reserved);

            foreach (var child in node.Children.Values)
                members.Declare(child.Name, source);

            foreach (var property in flat)
            {
                members.Declare(property.PropertyName, source);
                members.Declare(property.FieldName, source);
            }

            foreach (var pair in owners)
            {
                var ownerClass = pair.Key + "Sprites";
                members.Declare(pair.Key, source);
                members.Declare(ownerClass, source);

                var ownerMembers = new IdentifierScope(ownerClass,
                    new List<string>(CodeIdentifiers.InheritedMembers(typeof(object))) { "_group" });

                foreach (var property in pair.Value)
                {
                    ownerMembers.Declare(property.MemberName, $"{source}, animations of '{pair.Key}'");
                    ownerMembers.Declare(property.FieldName, $"{source}, animations of '{pair.Key}'");
                }
            }
        }

        // Animations of one Multiple Animations file. They are loaded together with the group,
        // so access to them checks that the group is loaded.
        private static void BuildOwnerClass(
            StringBuilder builder,
            string owner,
            IReadOnlyList<SpritePropertyDefinition> members)
        {
            builder.AppendLine($"        public sealed class {owner}Sprites {{");
            builder.AppendLine("            private readonly SpriteGroup _group;");
            builder.AppendLine();

            foreach (var property in members)
                builder.AppendLine($"            internal {PropertyType(property.Kind)} {property.FieldName};");

            builder.AppendLine();
            builder.AppendLine($"            internal {owner}Sprites(SpriteGroup group) {{");
            builder.AppendLine("                _group = group;");
            builder.AppendLine("            }");

            foreach (var property in members)
            {
                builder.AppendLine();
                builder.AppendLine($"            public {PropertyType(property.Kind)} {property.MemberName} {{");
                builder.AppendLine($"                get {{ _group.EnsureLoaded(); return {property.FieldName}; }}");
                builder.AppendLine("            }");
            }

            builder.AppendLine("        }");
        }

        private static string Getter(SpriteKind kind)
        {
            return kind == SpriteKind.Animation ? "GetAnimation" : "GetSheet";
        }

        private static string PropertyType(SpriteKind kind)
        {
            return kind == SpriteKind.Animation ? "ISpriteAnimationData" : "Sprite";
        }
    }
}
