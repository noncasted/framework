using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEngine;

namespace Internal
{
    public static class AssetsCatalogClassGenerator
    {
        public static string InternalGeneratedFolder => FrameworkSettings.Content("Runtime/Catalogues/Assets");

        // Catalog classes share the Generated folder with other generators, so our own files
        // are recognized by the name suffix.
        private const string OwnedSuffix = "Assets.cs";

        private const string LogTag = "AssetsCatalogClassGenerator";

        internal static void Generate(IReadOnlyList<AssetGroupDefinition> groups)
        {
            var byFolder = GeneratedFile.GroupByFolder(LogTag, groups, static group => group.SkipCodegen, static group => group.GeneratedFolder);

            var writtenFolders = new HashSet<string>(StringComparer.Ordinal);

            foreach (var pair in byFolder)
            {
                writtenFolders.Add(pair.Key);
                WriteFolder(pair.Key, pair.Value);
            }

            GeneratedFile.DeleteFromUnusedFolders(LogTag, InternalGeneratedFolder, OwnedSuffix, writtenFolders);
        }

        public static string GetAssemblyGeneratedFolder(string assemblyName)
        {
            return CatalogAssemblies.GetGeneratedFolder(LogTag, assemblyName, InternalGeneratedFolder);
        }

        private static void WriteFolder(string folder, List<AssetGroupDefinition> groups)
        {
            CatalogPaths.EnsureFolder(folder);

            // Every class is built before the first one is written: a name that does not fit C# stops the whole
            // folder, not half of it.
            var sources = new Dictionary<string, string>(StringComparer.Ordinal);

            foreach (var group in groups)
                sources.Add(group.ClassName + ".cs", BuildGroupClass(group));

            foreach (var pair in sources)
                GeneratedFile.WriteIfChanged(LogTag, $"{folder}/{pair.Key}", pair.Value);

            GeneratedFile.DeleteStale(LogTag, folder, new HashSet<string>(sources.Keys, StringComparer.Ordinal),
                OwnedSuffix);
        }

        internal static string BuildGroupClass(AssetGroupDefinition group)
        {
            DeclareMembers(group);

            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by AssetCatalogGenerator. Do not edit manually.");
            builder.AppendLine("using Cysharp.Threading.Tasks;");
            builder.AppendLine("using Unity.Scripting.LifecycleManagement;");
            builder.AppendLine();
            builder.AppendLine($"namespace {group.TargetNamespace} {{");
            builder.AppendLine("    [NoAutoStaticsCleanup]");
            builder.AppendLine($"    public static class {group.ClassName} {{");

            if (group.IsAddressable)
                builder.AppendLine($"        private const string Address = \"{group.Address}\";");
            else
                builder.AppendLine($"        private const string ResourcePath = \"{group.ResourcePath}\";");

            builder.AppendLine();

            foreach (var property in group.Properties)
                builder.AppendLine($"        private static global::{property.TypeFullName} {property.FieldName};");

            builder.AppendLine();
            builder.AppendLine("        public static global::Internal.EnvAssetGroup Group { get; } = new Loader();");
            builder.AppendLine();
            builder.AppendLine("        public static bool IsLoaded => Group.IsLoaded;");
            builder.AppendLine();

            foreach (var property in group.Properties)
            {
                builder.AppendLine($"        public static global::{property.TypeFullName} {property.PropertyName} {{");
                builder.AppendLine($"            get {{ Group.EnsureLoaded(); return {property.FieldName}; }}");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            builder.AppendLine("        private sealed class Loader : global::Internal.EnvAssetGroup {");
            builder.AppendLine($"            public override string Name => nameof({group.ClassName});");
            builder.AppendLine();

            if (group.IsAddressable)
            {
                builder.AppendLine("            protected override async UniTask LoadGroup() {");
                builder.AppendLine("                await LoadAsset(Address);");
                AppendFields(builder, group);
                builder.AppendLine("            }");
            }
            else
            {
                // A Resources group loads synchronously: both on Retain and on first access.
                builder.AppendLine("            public override bool IsAddressable => false;");
                builder.AppendLine();
                builder.AppendLine("            protected override UniTask LoadGroup() {");
                builder.AppendLine("                LoadImmediately();");
                builder.AppendLine("                return UniTask.CompletedTask;");
                builder.AppendLine("            }");
                builder.AppendLine();
                builder.AppendLine("            protected override void LoadImmediately() {");
                builder.AppendLine("                LoadResource(ResourcePath);");
                AppendFields(builder, group);
                builder.AppendLine("            }");
            }

            builder.AppendLine();
            builder.AppendLine("            protected override void UnloadGroup() {");

            foreach (var property in group.Properties)
                builder.AppendLine($"                {property.FieldName} = null;");

            builder.AppendLine("                UnloadAsset();");
            builder.AppendLine("            }");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        // The members the class writes itself, the property and the field of every asset. The fields are also
        // assigned inside Loader, where a member of EnvAssetGroup with the same name would win.
        private static void DeclareMembers(AssetGroupDefinition group)
        {
            var members = new IdentifierScope(group.ClassName,
                new[] { "Address", "ResourcePath", "Group", "IsLoaded", "Loader" });
            var loader = new IdentifierScope("Loader", CodeIdentifiers.InheritedMembers(typeof(EnvAssetGroup)));

            foreach (var property in group.Properties)
            {
                var source = $"Asset group '{group.Name}', asset '{property.PropertyName}'";
                members.Declare(property.PropertyName, source);
                members.Declare(property.FieldName, source);
                loader.Declare(property.FieldName, source);
            }
        }

        private static void AppendFields(StringBuilder builder, AssetGroupDefinition group)
        {
            foreach (var property in group.Properties)
                builder.AppendLine(
                    $"                {property.FieldName} = Asset.Get<global::{property.TypeFullName}>(\"{property.PropertyName}\");");
        }

    }
}