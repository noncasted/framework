using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;

namespace Internal
{
    // Scenes.X: the ContentScene of every scene of the scene folders outside the Build Settings, read from the ContentRoot
    // (CatalogContent) under the GUID of the scene.
    public static class ScenesClassGenerator
    {
        private const string LogTag = "ScenesClassGenerator";
        private const string ClassName = "Scenes";

        // 1_Intro.unity gives Scene1Intro.
        private const string DigitPrefix = "Scene";

        private static string OutputPath => FrameworkSettings.Content("Runtime/Catalogues/Scenes/Scenes.cs");

        public static void Generate(List<(string sceneName, string sceneGuid)> scenes)
        {
            var source = Build(scenes);

            // A project without scenes has no catalogue; one whose last scene is gone gets an empty one.
            if (scenes.Count == 0 && File.Exists(CatalogPaths.ToFullPath(OutputPath)) == false)
                return;

            GeneratedFile.WriteIfChanged(LogTag, OutputPath, source);
        }

        internal static string Build(List<(string sceneName, string sceneGuid)> scenes)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// Auto-generated by SceneGenerator. Do not edit manually.");
            sb.AppendLine("using Unity.Scripting.LifecycleManagement;");
            sb.AppendLine();
            sb.AppendLine("namespace Internal");
            sb.AppendLine("{");
            sb.AppendLine("    [NoAutoStaticsCleanup]");
            sb.AppendLine($"    public static class {ClassName}");
            sb.AppendLine("    {");

            var members = new IdentifierScope(ClassName, CodeIdentifiers.InheritedMembers(typeof(object)));

            // Ordinal: the order of the members must not depend on the culture of the machine.
            foreach (var (sceneName, sceneGuid) in scenes.OrderBy(s => s.sceneName, StringComparer.Ordinal))
            {
                var propertyName = CatalogNaming.ToIdentifier(sceneName, DigitPrefix);
                members.Declare(propertyName, $"Scene {AssetDatabase.GUIDToAssetPath(sceneGuid)}");
                sb.AppendLine($"        public static ContentScene {propertyName} => CatalogContent.Scene(\"{sceneGuid}\");");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }
    }
}