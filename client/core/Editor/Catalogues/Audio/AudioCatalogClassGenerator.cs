using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Internal
{
    public static class AudioCatalogClassGenerator
    {
        public static string GeneratedFolder => FrameworkSettings.Content("Runtime/Catalogues/Audio");

        // Clips are UnityEngine types, so the classes of all groups live in Internal rather than in module assemblies.
        private const string OwnedSuffix = "Audio.cs";

        private const string LogTag = "AudioCatalogClassGenerator";

        internal static void Generate(IReadOnlyList<AudioGroupDefinition> groups)
        {
            CatalogPaths.EnsureFolder(GeneratedFolder);

            // Every class is built before the first one is written: a name that does not fit C# stops the whole
            // catalogue, not half of it.
            var sources = new Dictionary<string, string>(StringComparer.Ordinal);

            foreach (var group in groups)
                sources.Add(group.ClassName + ".cs", BuildGroupClass(group));

            foreach (var pair in sources)
                GeneratedFile.WriteIfChanged(LogTag, $"{GeneratedFolder}/{pair.Key}", pair.Value);

            GeneratedFile.DeleteStale(LogTag, GeneratedFolder,
                new HashSet<string>(sources.Keys, StringComparer.Ordinal), OwnedSuffix);
        }

        internal static string BuildGroupClass(AudioGroupDefinition group)
        {
            const string soundType = "global::Internal.Sound";
            const string listType = "global::System.Collections.Generic.IReadOnlyList<global::Internal.Sound>";

            // Variations are exposed only as a list; individual clips from them are not exposed.
            var singles = group.Properties.Where(property => property.Variation == null).ToList();

            DeclareMembers(group, singles);

            var builder = new StringBuilder();
            builder.AppendLine("// Auto-generated by AudioCatalogGenerator. Do not edit manually.");
            builder.AppendLine("using Cysharp.Threading.Tasks;");
            builder.AppendLine("using Unity.Scripting.LifecycleManagement;");
            builder.AppendLine();
            builder.AppendLine("namespace Internal {");
            builder.AppendLine("    [NoAutoStaticsCleanup]");
            builder.AppendLine($"    public static class {group.ClassName} {{");
            builder.AppendLine($"        private const string Address = \"{group.Address}\";");
            builder.AppendLine();

            foreach (var property in singles)
                builder.AppendLine($"        private static {soundType} {property.FieldName};");

            foreach (var variation in group.Variations)
                builder.AppendLine($"        private static {soundType}[] {variation.FieldName};");

            builder.AppendLine();
            builder.AppendLine("        public static AudioGroup Group { get; } = new Loader();");
            builder.AppendLine();
            builder.AppendLine("        public static bool IsLoaded => Group.IsLoaded;");
            builder.AppendLine();

            foreach (var property in singles)
            {
                builder.AppendLine($"        public static {soundType} {property.PropertyName} {{");
                builder.AppendLine($"            get {{ Group.EnsureLoaded(); return {property.FieldName}; }}");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            foreach (var variation in group.Variations)
            {
                builder.AppendLine($"        public static {listType} {variation.PropertyName} {{");
                builder.AppendLine($"            get {{ Group.EnsureLoaded(); return {variation.FieldName}; }}");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            builder.AppendLine("        private sealed class Loader : AudioGroup {");
            builder.AppendLine($"            public override string Name => nameof({group.ClassName});");
            builder.AppendLine();
            builder.AppendLine("            protected override async UniTask LoadGroup() {");
            builder.AppendLine("                await LoadAsset(Address);");
            builder.AppendLine("                await Asset.Decode();");

            foreach (var property in singles)
                builder.AppendLine($"                {property.FieldName} = Asset.Get(\"{property.PropertyName}\");");

            foreach (var variation in group.Variations)
            {
                builder.AppendLine($"                {variation.FieldName} = new[] {{");

                foreach (var entry in variation.Entries)
                    builder.AppendLine($"                    Asset.Get(\"{entry.PropertyName}\"),");

                builder.AppendLine("                };");
            }

            builder.AppendLine("            }");
            builder.AppendLine();
            builder.AppendLine("            protected override void UnloadGroup() {");

            foreach (var property in singles)
                builder.AppendLine($"                {property.FieldName} = null;");

            foreach (var variation in group.Variations)
                builder.AppendLine($"                {variation.FieldName} = null;");

            builder.AppendLine("                Asset.ReleaseDecoded();");
            builder.AppendLine("                UnloadAsset();");
            builder.AppendLine("            }");
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        // The members the class writes itself, the property and the field of every clip and variation list. The
        // fields are also assigned inside Loader, where a member of AudioGroup with the same name would win.
        private static void DeclareMembers(AudioGroupDefinition group, List<AudioPropertyDefinition> singles)
        {
            var members = new IdentifierScope(group.ClassName, new[] { "Address", "Group", "IsLoaded", "Loader" });
            var loader = new IdentifierScope("Loader", CodeIdentifiers.InheritedMembers(typeof(AudioGroup)));

            var names = singles.Select(property => (property.PropertyName, property.FieldName))
                .Concat(group.Variations.Select(variation => (variation.PropertyName, variation.FieldName)));

            foreach (var (propertyName, fieldName) in names)
            {
                var source = $"Audio group '{group.Name}', sound '{propertyName}'";
                members.Declare(propertyName, source);
                members.Declare(fieldName, source);
                loader.Declare(fieldName, source);
            }
        }
    }
}
