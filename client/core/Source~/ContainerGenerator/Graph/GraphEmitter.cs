using System;
using System.Collections.Generic;
using System.Globalization;
using Microsoft.CodeAnalysis;

namespace ContainerGenerator {
    internal static class GraphEmitter {
        public const string AttributeMetadataName = "Internal.ContainerInstallerAttribute";

        public static string Emit(GraphDocument document, Compilation? compilation) {
            var writer = new CodeWriter();
            writer.AppendLine("// <auto-generated/>");
            writer.AppendLine("#pragma warning disable");
            writer.AppendLine();

            var types = compilation != null ? new TypeIndex(compilation) : null;
            for (var i = 0; i < document.Methods.Count; i++) {
                var method = document.Methods[i];
                if (ManifestHarvest.IsHarvest(method.Id))
                    continue;
                if (string.IsNullOrEmpty(method.Variant) == false)
                    continue;
                if (string.IsNullOrEmpty(method.AssemblyName) == false &&
                    string.IsNullOrEmpty(document.AssemblyName) == false &&
                    string.Equals(method.AssemblyName, document.AssemblyName, StringComparison.Ordinal) == false)
                    continue;
                WriteAssemblyAttribute(writer, method, types);
            }

            return writer.ToString();
        }

        private static void WriteAssemblyAttribute(CodeWriter writer, GraphMethod method, TypeIndex? types) {
            var implementations = new List<string>();
            var services = new List<string>();
            for (var i = 0; i < method.Registrations.Count; i++) {
                var registration = method.Registrations[i];
                implementations.Add(TypeOf(types, TypeOfTarget(registration.ImplementationType, registration.TypeMap)));
                for (var s = 0; s < registration.ServiceTypes.Count; s++) {
                    var map = s < registration.ServiceMaps.Count ? registration.ServiceMaps[s] : "";
                    services.Add(TypeOf(types, TypeOfTarget(registration.ServiceTypes[s], map)));
                }
            }

            writer.AppendLine("[assembly: global::Internal.ContainerInstaller(");
            writer.AppendLine("    " + EmitLiterals.Literal(method.Id) + ",");
            writer.AppendLine("    " + (method.IsRoot ? "true" : "false") + ",");
            writer.AppendLine("    " + EmitLiterals.Literal(method.File) + ",");
            writer.AppendLine("    " + method.Line.ToString(CultureInfo.InvariantCulture) + ",");
            WriteTypeArray(writer, implementations);
            writer.AppendLine(",");
            WriteTypeArray(writer, services);
            writer.AppendLine(",");
            writer.AppendLine("    new string[] {");
            for (var i = 0; i < method.Calls.Count; i++) {
                var comma = i + 1 < method.Calls.Count ? "," : "";
                writer.AppendLine("        " + EmitLiterals.Literal(method.Calls[i]) + comma);
            }

            writer.AppendLine("    },");
            writer.AppendLine("    " + EmitLiterals.Literal(ManifestBlobWriter.WriteBlob(method)) + ")]");
        }

        private static void WriteTypeArray(CodeWriter writer, List<string> types) {
            writer.AppendLine("    new global::System.Type[] {");
            for (var i = 0; i < types.Count; i++) {
                var comma = i + 1 < types.Count ? "," : "";
                var type = types[i] == ManifestBlobFormat.VoidSentinel ? "void" : types[i];
                writer.AppendLine("        typeof(" + type + ")" + comma);
            }

            writer.AppendLine("    }");
        }

        private static string TypeOfTarget(string template, string map) {
            if (string.IsNullOrEmpty(map) == false && map[0] == 'T')
                return "";
            if (string.IsNullOrEmpty(template) || template.IndexOf('{') < 0)
                return template;
            return TypeSubstitution.ToUnbound(template);
        }

        private static string TypeOf(TypeIndex? types, string fullyQualified) {
            if (string.IsNullOrEmpty(fullyQualified))
                return ManifestBlobFormat.VoidSentinel;
            if (types == null)
                return fullyQualified;

            var symbol = types.Find(fullyQualified);
            if (symbol != null) {
                if (symbol.IsGenericType &&
                    (symbol.IsUnboundGenericType || LooksUnbound(fullyQualified) || ContainsTypeParameter(symbol))) {
                    var unbound = symbol.IsUnboundGenericType ? symbol : symbol.ConstructUnboundGenericType();
                    return TypeNames.ForCode(unbound);
                }

                if (ContainsTypeParameter(symbol))
                    return ManifestBlobFormat.VoidSentinel;
                return TypeNames.ForCode(symbol);
            }

            return ContainsPlaceholder(fullyQualified) ? ManifestBlobFormat.VoidSentinel : fullyQualified;
        }

        private static bool LooksUnbound(string type) {
            return string.IsNullOrEmpty(type) == false &&
                   (type.IndexOf("<>", StringComparison.Ordinal) >= 0 ||
                    type.IndexOf("<,", StringComparison.Ordinal) >= 0);
        }

        private static bool ContainsPlaceholder(string value) {
            return string.IsNullOrEmpty(value) == false && value.IndexOf('{') >= 0;
        }

        private static bool ContainsTypeParameter(ITypeSymbol type) {
            if (type == null)
                return false;
            if (type is ITypeParameterSymbol)
                return true;
            if (type is INamedTypeSymbol named) {
                if (named.IsUnboundGenericType)
                    return false;
                for (var i = 0; i < named.TypeArguments.Length; i++) {
                    if (ContainsTypeParameter(named.TypeArguments[i]))
                        return true;
                }
            }

            if (type is IArrayTypeSymbol array)
                return ContainsTypeParameter(array.ElementType);
            return false;
        }
    }
}
