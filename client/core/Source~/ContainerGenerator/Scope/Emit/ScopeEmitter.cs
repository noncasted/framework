using Microsoft.CodeAnalysis;

namespace ContainerGenerator {
    internal static class ScopeEmitter {
        public static bool TryEmit(
            ScopeGraph graph,
            GraphDocument document,
            Compilation compilation,
            ReferenceSymbols references,
            out string hintName,
            out string source) {
            hintName = "";
            source = "";
            var plan = ScopePlanBuilder.Build(graph, document, compilation, references);
            if (plan == null)
                return false;

            hintName = plan.HintName;
            source = Write(plan, graph);
            return string.IsNullOrEmpty(source) == false;
        }

        private static string Write(ScopePlan plan, ScopeGraph graph) {
            var writer = new CodeWriter();
            writer.AppendLine("// <auto-generated/>");
            writer.AppendLine("#pragma warning disable");
            writer.AppendLine();

            var bases = "global::Internal.IContainer";
            for (var i = 0; i < plan.Provides.Count; i++)
                bases += ", global::Internal.IProvides<" + plan.Provides[i].TargetType + ">";

            if (string.IsNullOrEmpty(plan.Namespace) == false) {
                writer.AppendLine("namespace " + plan.Namespace + " {");
                WriteClass(writer, plan, graph, bases, "    ");
                writer.AppendLine("}");
            }
            else {
                WriteClass(writer, plan, graph, bases, "");
            }

            return writer.ToString();
        }

        private static void WriteClass(
            CodeWriter writer,
            ScopePlan plan,
            ScopeGraph graph,
            string bases,
            string indent) {
            var deeper = indent + "    ";
            var body = indent + "        ";
            writer.AppendLine(indent + "internal sealed class " + plan.ClassName + " : " + bases + " {");
            ConstructorWriter.WriteConstructor(writer, plan, graph, deeper, body);
            writer.AppendLine();
            FieldsWriter.WriteFields(writer, plan, deeper);
            writer.AppendLine();
            ContainerApiWriter.WriteContainerApi(writer, plan, graph, deeper, body);
            RegisterWriter.WriteRegister(writer, plan, graph, deeper, body);
            FactoryWriter.WriteFactories(writer, plan, graph, deeper, body);
            FactoryWriter.WriteProvides(writer, plan, graph, deeper, body);
            DiagnosticsWriter.WriteDiagnostics(writer, plan, graph, deeper, body);
            writer.AppendLine(indent + "}");
        }
    }
}
