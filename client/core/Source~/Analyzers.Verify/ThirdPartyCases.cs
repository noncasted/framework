using System.Text;

namespace Framework.Analyzers.Verify
{
    // Third-party code (Library/PackageCache, a package folder inside Packages / packages, Assets/Plugins) and generated
    // code get no rule; framework_rules.third_party of .editorconfig wins over the path.
    internal static class ThirdPartyCases
    {
        private const string AllRules = "FWR001+FWR002+FWR003+FWR004+FWR005+FWR006";

        // Every rule fires on it outside third-party code; the interface on line 1 is the main type of the file.
        private static readonly string _violations = @"namespace Internal { public interface IReadOnlyLifetime { } }

// Комментарий
public class Holder
{
    public int Value;
}
public class Second { }
public class Locker { public void Use(Internal.IReadOnlyLifetime lifetime) { lock (lifetime) { } } }
" + Padding(300);

        private static readonly string[] _all = { "FWR001@6", "FWR002@1", "FWR003@4", "FWR003@8", "FWR003@9", "FWR004@3", "FWR005@9", "FWR006@1" };

        public static void Run(Harness harness)
        {
            harness.Case(AllRules + " runtime code of a game", One("Assets/Game/File.cs"), _all);
            harness.Case(AllRules + " code of the framework", One("tools/framework/client/core/Runtime/File.cs"), _all);

            harness.Case(AllRules + " forks of the framework", One("tools/framework/client/packages/com.cysharp.unitask/Runtime/File.cs"),
                new string[0]);
            harness.Case(AllRules + " embedded package of a game", One("client/Packages/com.unity.ugui/Runtime/File.cs"), new string[0]);
            harness.Case(AllRules + " registry package", One("client/Library/PackageCache/com.unity.collections@1a2b/Unity.Collections/File.cs"),
                new string[0]);
            harness.Case(AllRules + " plugins of a game", One("client/Assets/Plugins/RedBlueGames/Editor/File.cs"), new string[0]);

            harness.Case(AllRules + " a folder Packages without a package folder", One("Packages/Runtime/File.cs"), _all);
            harness.Case(AllRules + " a folder Plugins outside Assets", One("Assets/Game/Plugins/File.cs"), _all);

            harness.Case(AllRules + " framework_rules.third_party = true", One("Assets/Game/File.cs"), new string[0],
                editorConfig: "framework_rules.third_party = true\n");
            harness.Case(AllRules + " framework_rules.third_party = false in a fork", One("client/packages/com.cysharp.unitask/File.cs"), _all,
                editorConfig: "framework_rules.third_party = false\n");

            harness.Case(AllRules + " <auto-generated/> before the line of the generator",
                new[] { new Source("Assets/Game/File.cs", "// <auto-generated/>\n// Auto-generated by X. Do not edit manually.\n" + _violations) },
                new string[0]);
        }

        private static Source[] One(string path)
        {
            return new[] { new Source(path, _violations) };
        }

        private static string Padding(int count)
        {
            var builder = new StringBuilder();

            for (var i = 0; i < count; i++)
                builder.Append("// line\n");

            return builder.ToString();
        }
    }
}
