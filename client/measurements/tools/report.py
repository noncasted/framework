#!/usr/bin/env python3
"""Rebuilds RESULTS.md from results/<version>/<variant>.json (written by measure.py). Run alone after editing a
result by hand; measure.py runs it after every measurement.

The download is what a player loads: the wasm, the data, the framework, the loader and StreamingAssets (the catalog
and the bundles of Addressables), compressed as served
(the symbols file is not loaded by the page and is listed apart). Sizes are KiB (1024 bytes)."""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOWNLOADED = ('wasm', 'data', 'framework', 'loader', 'streaming')
BASELINE_VARIANT = 'base'


def main():
    results = load()
    versions = sorted({r['unity'] for r in results}, key=version_key)
    variants = sorted({r['variant'] for r in results}, key=lambda v: (v != BASELINE_VARIANT, v))
    by_key = {(r['unity'], r['variant']): r for r in results}

    lines = [
        '# WebGL build size: results',
        '',
        'Generated by `tools/report.py` from `results/<version>/<variant>.json`; do not edit by hand. '
        'How the numbers are made: [README.md](README.md). KiB, brotli as served unless marked raw.',
        '',
    ]

    lines += summary_table(versions, variants, by_key)
    lines += variant_savings(versions, variants, by_key)
    lines += version_changes(versions, variants, by_key)
    lines += wasm_table(versions, variants, by_key)
    lines += data_table(versions, variants, by_key)
    lines += managed_table(versions, variants, by_key)
    lines += runs_table(versions, variants, by_key)
    lines += profiles_table()

    with open(os.path.join(ROOT, 'RESULTS.md'), 'w') as file:
        file.write('\n'.join(lines).rstrip() + '\n')


def load():
    results = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'results', '*', '*.json'))):
        with open(path) as file:
            results.append(json.load(file))
    return results


def version_key(version):
    match = re.match(r'(\d+)\.(\d+)\.(\d+)([abfp])(\d+)', version)
    if not match:
        return (version,)
    major, minor, patch, stage, number = match.groups()
    return int(major), int(minor), int(patch), 'abfp'.index(stage), int(number)


def kib(value):
    return f'{value / 1024:,.0f}'


def signed_kib(value):
    return f'{value / 1024:+,.0f}'


def percent(part, whole):
    return f'{part * 100 / whole:+.1f}%' if whole else '-'


def size(result, kind, field='compressed'):
    return sum(f[field] for f in result['files'] if f['kind'] == kind)


def download(result, field='compressed'):
    return sum(size(result, kind, field) for kind in DOWNLOADED)


def smoke_text(result):
    smoke = result.get('smoke')
    if smoke is None:
        return 'not run'
    return f'{smoke["status"]} ({smoke["seconds"]} s)' if smoke['status'] == 'ready' else f'**{smoke["status"]}**'


def summary_table(versions, variants, by_key):
    lines = ['## Sizes', '',
             '| Unity | Variant | Download | wasm | data | framework.js | StreamingAssets | wasm raw | wasm before submodule stripping | Smoke |',
             '|---|---|---:|---:|---:|---:|---:|---:|---:|---|']
    for version in versions:
        for variant in variants:
            r = by_key.get((version, variant))
            if not r:
                continue
            before = r['wasmBeforeStripping']['compressed']
            lines.append(f'| {version} | {variant} | **{kib(download(r))}** | {kib(size(r, "wasm"))} | {kib(size(r, "data"))} | '
                         f'{kib(size(r, "framework"))} | {kib(size(r, "streaming"))} | {kib(size(r, "wasm", "raw"))} | {kib(before)} '
                         f'({signed_kib(size(r, "wasm") - before)}) | {smoke_text(r)} |')
    return lines + ['']


def variant_savings(versions, variants, by_key):
    lines = [f'## Saved against `{BASELINE_VARIANT}`', '',
             '| Unity | Variant | Download | wasm | data | framework.js |', '|---|---|---:|---:|---:|---:|']
    rows = 0
    for version in versions:
        base = by_key.get((version, BASELINE_VARIANT))
        for variant in variants:
            r = by_key.get((version, variant))
            if not base or not r or variant == BASELINE_VARIANT:
                continue
            rows += 1
            lines.append(f'| {version} | {variant} | {delta(download(r), download(base))} | '
                         + ' | '.join(delta(size(r, kind), size(base, kind)) for kind in ('wasm', 'data', 'framework')) + ' |')
    return lines + [''] if rows else []


def version_changes(versions, variants, by_key):
    if len(versions) < 2:
        return []
    first = versions[0]
    lines = [f'## Changed against Unity {first}', '',
             '| Unity | Variant | Download | wasm | data | framework.js | managed assemblies (raw) |',
             '|---|---|---:|---:|---:|---:|---:|']
    for version in versions[1:]:
        for variant in variants:
            r, old = by_key.get((version, variant)), by_key.get((first, variant))
            if not r or not old:
                continue
            lines.append(f'| {version} | {variant} | {delta(download(r), download(old))} | '
                         + ' | '.join(delta(size(r, kind), size(old, kind)) for kind in ('wasm', 'data', 'framework'))
                         + f' | {delta(sum(r["managed"].values()), sum(old["managed"].values()))} |')
    return lines + ['']


def delta(value, reference):
    return f'{signed_kib(value - reference)} ({percent(value - reference, reference)})'


def wasm_table(versions, variants, by_key):
    lines = ['## Sections of the wasm (raw)', '',
             'code: the compiled engine and IL2CPP code; data: its constants (the IL2CPP metadata is in the .data file).', '',
             '| Unity | Variant | code | data | other |', '|---|---|---:|---:|---:|']
    for version in versions:
        for variant in variants:
            r = by_key.get((version, variant))
            if not r:
                continue
            sections = next(f['sections'] for f in r['files'] if f['kind'] == 'wasm')
            other = sum(v for k, v in sections.items() if k not in ('code', 'data'))
            lines.append(f'| {version} | {variant} | {kib(sections.get("code", 0))} | {kib(sections.get("data", 0))} | {kib(other)} |')
    return lines + ['']


DATA_GROUPS = (
    ('IL2CPP metadata', lambda name: name.startswith('Il2CppData/Metadata/')),
    ('ICU (globalization)', lambda name: name.startswith('Il2CppData/Icu/')),
    ('resources of assemblies', lambda name: name.startswith('Il2CppData/Resources/')),
    ('scene and assets', lambda name: name in ('data.unity3d', 'Resources/unity default resources') or name.startswith('sharedassets')),
)


def data_group(name):
    return next((group for group, matches in DATA_GROUPS if matches(name)), 'other')


def data_table(versions, variants, by_key):
    """The .data file by its contents: brotli of each part compressed alone (an estimate), raw in brackets."""
    groups = [group for group, _ in DATA_GROUPS] + ['other']
    lines = ['## Contents of the data file', '',
             'brotli of each part compressed alone (an estimate, raw in brackets).', '',
             '| Unity | Variant | ' + ' | '.join(groups) + ' |', '|---|---|' + '---:|' * len(groups)]
    for version in versions:
        for variant in variants:
            r = by_key.get((version, variant))
            if not r:
                continue
            contents = next(f for f in r['files'] if f['kind'] == 'data').get('contents')
            if contents is None:
                continue
            cells = []
            for group in groups:
                parts = [c for c in contents if data_group(c['name']) == group]
                cells.append(f'{kib(sum(c["compressed"] for c in parts))} ({kib(sum(c["raw"] for c in parts))})' if parts else '-')
            lines.append(f'| {version} | {variant} | ' + ' | '.join(cells) + ' |')
    return lines + ['']


def managed_table(versions, variants, by_key):
    """The largest assemblies after the IL2CPP linker, side by side for the versions: where the BCL changes show."""
    lines = []
    for variant in variants:
        present = [v for v in versions if (v, variant) in by_key]
        if not present:
            continue
        names = {}
        for version in present:
            for name, value in by_key[(version, variant)]['managed'].items():
                names[name] = max(names.get(name, 0), value)
        top = sorted(names, key=lambda name: -names[name])[:15]
        lines += [f'## Managed assemblies after the linker, `{variant}` (raw)', '',
                  '| Assembly | ' + ' | '.join(present) + ' |', '|---|' + '---:|' * len(present)]
        for name in top:
            lines.append(f'| {name} | ' + ' | '.join(
                kib(by_key[(v, variant)]['managed'][name]) if name in by_key[(v, variant)]['managed'] else '-' for v in present) + ' |')
        lines.append('| **all** | ' + ' | '.join(f'**{kib(sum(by_key[(v, variant)]["managed"].values()))}**' for v in present) + ' |')
        lines.append('')
    return lines


def runs_table(versions, variants, by_key):
    lines = ['## Runs', '', '| Unity | Variant | Measured | Build | Submodules stripped | Skipped (absent in the version) | Overrides | Smoke line |',
             '|---|---|---|---:|---:|---|---|---|']
    for version in versions:
        for variant in variants:
            r = by_key.get((version, variant))
            if not r:
                continue
            smoke = r.get('smoke') or {}
            line = (smoke.get('line') or '').replace('|', '/')
            lines.append(f'| {version} | {variant} | {r["measured"]} | {r["build"]["buildSeconds"]:.0f} s | '
                         f'{r["build"]["strippedSubmodules"]} | {", ".join(r["strippingSkipped"]) or "-"} | '
                         f'{"; ".join(r.get("overrides", [])).replace("|", "/") or "-"} | {line} |')
    return lines + ['']


def profiles_table():
    """profiles/<version>/<variant>.json of measure.py --profile: what the scene called in an unstripped build."""
    paths = sorted(glob.glob(os.path.join(ROOT, 'profiles', '*', '*.json')))
    if not paths:
        return []
    lines = ['## Submodule profiling', '',
             'The submodules an instrumented unstripped build called during the smoke run (`--profile`). Candidates: never '
             'called and not stripped by the lists of the variant; called but stripped: the lists strip a submodule the '
             'scene calls (alive only through `Ignore`).', '',
             '| Unity | Variant | Measured | Called | Candidates | Called but stripped |', '|---|---|---|---:|---|---|']
    profiles = [json.load(open(path)) for path in paths]
    for p in sorted(profiles, key=lambda p: (version_key(p['unity']), p['variant'])):
        lines.append(f'| {p["unity"]} | {p["variant"]} | {p["measured"]} | {len(p["used"])} | '
                     f'{", ".join(p["candidates"]) or "-"} | {", ".join(p["calledButStripped"]) or "-"} |')
    return lines + ['']


if __name__ == '__main__':
    main()
